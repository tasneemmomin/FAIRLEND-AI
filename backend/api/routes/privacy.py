@router.post("/export/{application_id}")
def export_applicant_data(application_id: str, db: Session = Depends(get_db)):
    """Exports all personal data held for an applicant (DPDP Act right to data portability)."""
    app = db.query(Application).filter(Application.id == application_id).first()
    if not app:
        raise HTTPException(status_code=404, detail="Application not found")

    snapshot = app.feature_snapshots[0] if app.feature_snapshots else None

    # Log audit event
    audit = AuditLog(
        user_role="applicant",
        user_id=app.id,
        action="privacy_exported",
        resource_id=app.id,
        details={"timestamp": datetime.now(timezone.utc).isoformat()}
    )
    db.add(audit)
    db.commit()

    return {
        "export_timestamp": datetime.now(timezone.utc).isoformat(),
        "application_id": app.id,
        "personal_profile": {
            "name": decrypt_field(app.applicant_name_enc),
            "phone": decrypt_field(app.contact_phone_enc),
            "email": decrypt_field(app.contact_email_enc),
            "age": app.age,
            "employment_type": app.employment_type,
            "employment_duration_months": app.employment_duration_months,
            "monthly_income": app.monthly_income,
            "existing_emis": app.existing_emis,
            "requested_amount": app.requested_amount,
            "tenure_months": app.tenure_months,
            "loan_purpose": app.loan_purpose,
            "intake_transcript": app.intake_transcript
        },
        "feature_snapshot": snapshot.feature_vector if snapshot else {},
        "calculated_ratios": {
            "foir": snapshot.foir if snapshot else 0.0,
            "lti": snapshot.lti if snapshot else 0.0,
            "disposable_income": snapshot.disposable_income if snapshot else 0.0,
            "consistency_score": app.consistency_score
        },
        "ai_recommendation": {
            "status": app.status,
            "code": app.ai_recommendation,
            "confidence": app.ai_confidence,
            "reasons": app.ai_recommendation_reasons or []
        },
        "officer_decision": {
            "decision": app.decision.decision if app.decision else "Pending",
            "reason_code": app.decision.reason_code if app.decision else None,
            "timestamp": app.decision.decision_timestamp.isoformat() if app.decision else None
        }
    }

@router.post("/delete/{application_id}")
def delete_applicant_data(application_id: str, db: Session = Depends(get_db)):
    """Erases and anonymizes applicant personal data (DPDP Act right to erasure)."""
    app = db.query(Application).filter(Application.id == application_id).first()
    if not app:
        raise HTTPException(status_code=404, detail="Application not found")

    # Anonymize PII
    app.applicant_name_enc = None
    app.contact_phone_enc = None
    app.contact_email_enc = None
    app.intake_transcript = "[Erased per DPDP Act request]"

    # If fairness audit record exists, remove demographic link
    if app.fairness_record:
        app.fairness_record.gender = "redacted"
        app.fairness_record.social_group = "redacted"

    audit = AuditLog(
        user_role="applicant",
        user_id=app.id,
        action="privacy_erased",
        resource_id=app.id,
        details={"timestamp": datetime.now(timezone.utc).isoformat()}
    )
    db.add(audit)
    db.commit()

    return {
        "status": "success",
        "message": "Applicant personal identifying data has been permanently erased in compliance with DPDP Act 2023.",
        "application_id": app.id
    }
